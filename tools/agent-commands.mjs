// Writes the framework's commands in each AI coding agent's own format.
//
// **One source, every agent.** Each command is a pointer to a procedure in
// `ai-only/procedures/`, and `.claude/commands/<name>.md` already says which
// procedure and what it is for. This renders the same pointer for the agents
// that read their own command files, so `/build` (or `$build`) works there
// too, and follows the same procedure text rather than a copy of it.
//
// The agents and their formats are in bin/agents.mjs.
//
//   node tools/agent-commands.mjs           # write them
//   node tools/agent-commands.mjs --check   # exit 1 if any is out of date

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { AGENTS } from "../bin/agents.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");


const HEADER = "Generated by CooperativeAICoding from .claude/commands — run tools/agent-commands.mjs, don't edit.";

function body(name, args) {
  const forWhat = args ? `for: ${args}` : "for what the user asked in this conversation.";
  return (
    `Follow **\`ai-only/procedures/${name}.md\`** exactly, ${forWhat}\n\n` +
    `Resolve it under the project root you are working in — in the framework's own\n` +
    `repository that is \`template/ai-only/procedures/${name}.md\`. The procedure is\n` +
    `the instruction; this file only points at it.\n`
  );
}

const quote = (s) => JSON.stringify(s);

function render(agent, name, description) {
  const { kind, args } = AGENTS[agent];
  if (kind === "skill") {
    return `---\nname: ${name}\ndescription: ${quote(description)}\n---\n\n<!-- ${HEADER} -->\n\n${body(name, args)}`;
  }
  if (kind === "toml") {
    return `# ${HEADER}\ndescription = ${quote(description)}\nprompt = """\n${body(name, args)}"""\n`;
  }
  if (kind === "markdown") {
    return `---\ndescription: ${quote(description)}\n---\n\n<!-- ${HEADER} -->\n\n${body(name, args)}`;
  }
  return `<!-- ${HEADER} -->\n\n${description}\n\n${body(name, args)}`;
}

/** Every agent's command file, as { path, content }. */
export async function generate() {
  const dir = path.join(repo, ".claude/commands");
  const out = [];
  for (const file of (await fs.readdir(dir)).filter((f) => f.endsWith(".md")).sort()) {
    const name = file.replace(/\.md$/, "");
    const text = (await fs.readFile(path.join(dir, file), "utf8")).replace(/\r\n/g, "\n");
    const description = text.match(/\ndescription: (.+)\n/)?.[1]?.trim();
    if (!description) throw new Error(`.claude/commands/${file} has no description`);
    for (const agent of Object.keys(AGENTS).filter((a) => AGENTS[a].kind)) {
      out.push({ path: `${AGENTS[agent].dir}/${AGENTS[agent].file(name)}`, content: render(agent, name, description) });
    }
  }
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = await generate();
  if (process.argv.includes("--check")) {
    const stale = [];
    for (const f of files) {
      const now = await fs.readFile(path.join(repo, f.path), "utf8").then((t) => t.replace(/\r\n/g, "\n"), () => null);
      if (now !== f.content) stale.push(f.path);
    }
    if (stale.length > 0) {
      console.log(`out of date — run node tools/agent-commands.mjs:\n  ${stale.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`${files.length} agent command file(s) up to date`);
  } else {
    for (const f of files) {
      await fs.mkdir(path.dirname(path.join(repo, f.path)), { recursive: true });
      await fs.writeFile(path.join(repo, f.path), f.content);
    }
    console.log(`wrote ${files.length} agent command file(s)`);
  }
}
