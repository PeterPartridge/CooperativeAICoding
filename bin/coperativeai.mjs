#!/usr/bin/env node
// Puts the framework into a project, and later brings it up to date.
//
// **Why this exists.** Every comparable tool starts with one command, and this
// one started with a clone, a copy, and a twenty-question form. The first ten
// minutes decide whether anybody reaches the part that is actually good, and
// a folder copy is a poor use of them.
//
// **`init` writes, it never overwrites.** A file that already exists is left
// exactly as it is and named in the report.
//
// **`update` brings framework fixes in without touching anybody's work.** It
// can tell a file nobody changed from one somebody edited, because `init` and
// `update` record a fingerprint of every file they write in
// `.coperativeai.json`. A framework file whose fingerprint still matches is
// replaced; an edited one is kept, with the new version written beside it as
// `<file>.update`; a file people fill in — the Project Brief, AGENTS.md, QA's
// suite and sign-off — is added if missing and otherwise never touched.
//
// No dependencies, on purpose: this is installed on somebody else's machine,
// and the thing it is asking for is trust.
//
//   npm install -g coperativeai
//   coperativeai init [folder] [--dry-run]
//   coperativeai update [folder] [--dry-run]

import { existsSync, promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { files, fingerprint } from "./layout.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const framework = path.resolve(here, "..");
const { version } = JSON.parse(await fs.readFile(path.join(framework, "package.json"), "utf8"));

// What a project receives is package.json's `files`; bin/layout.mjs says how
// each entry lands and who owns it.

const RECORD = ".coperativeai.json";

/** Every version the framework ever shipped, by fingerprint — how a project
 *  from before the install record still gets its untouched files updated.
 *  Written by tools/known-versions.mjs. */
const known = await fs
  .readFile(path.join(here, "known-versions.json"), "utf8")
  .then(JSON.parse, () => ({}));

/** The starter AGENTS.md says in its first line that it is generated and may
 *  be replaced; one emitted from the project's own spec says the same about
 *  that spec. Only the first is still the framework's to replace. */
const STARTER = /^<!-- Generated by CooperativeAICoding from template\//;

async function readRecord(root) {
  try {
    return JSON.parse(await fs.readFile(path.join(root, RECORD), "utf8"));
  } catch {
    return null;
  }
}

async function writeRecord(root, record) {
  const sorted = Object.fromEntries(Object.entries(record.files).sort(([a], [b]) => a.localeCompare(b)));
  await fs.writeFile(path.join(root, RECORD), JSON.stringify({ framework: version, files: sorted }, null, 2) + "\n");
}

async function write(to, content) {
  await fs.mkdir(path.dirname(to), { recursive: true });
  await fs.writeFile(to, content);
}

function list(label, items, max = 12) {
  if (items.length === 0) return;
  console.log(`\n${label}: ${items.length} file(s)`);
  for (const f of items.slice(0, max)) console.log(`  ${f}`);
  if (items.length > max) console.log(`  … and ${items.length - max} more`);
}

async function init(target, dryRun) {
  const root = path.resolve(target ?? ".");
  const record = (await readRecord(root)) ?? { files: {} };
  const written = [];
  const kept = [];

  for (const { from, to } of await files(framework)) {
    const src = await fs.readFile(path.join(framework, from));
    const dest = path.join(root, to);
    if (existsSync(dest)) {
      // Already there: left alone. Recorded only if it is the framework's copy
      // exactly, so a later update knows it may replace it.
      kept.push(to);
      if (fingerprint(await fs.readFile(dest)) === fingerprint(src)) record.files[to] = fingerprint(src);
      continue;
    }
    written.push(to);
    if (!dryRun) await write(dest, src);
    record.files[to] = fingerprint(src);
  }

  const verb = dryRun ? "would write" : "wrote";
  console.log(`\n${verb} ${written.length} file(s) into ${root}`);
  for (const f of written.slice(0, 12)) console.log(`  ${f}`);
  if (written.length > 12) console.log(`  … and ${written.length - 12} more`);
  // **Named, not silently skipped.** "It already ran and did nothing" and
  // "it left your answers alone" look identical in a summary count.
  list("left alone, already there", kept, 6);

  if (dryRun) {
    console.log("\nDry run — nothing was written. Drop --dry-run to do it.");
    return;
  }
  await fs.mkdir(root, { recursive: true });
  await writeRecord(root, record);

  console.log(`
Next, in that folder:

  1. Answer Project_brief.md in plain English. Lines starting with ">" are
     guidance; everything else you write is your answer. Set status: filled.
     Already have a codebase? Start Claude Code and run /draft instead — it
     fills the brief in from the code, says where each answer came from, and
     asks you a handful of multiple-choice questions rather than twenty open
     ones. Its answers are marked as its own until you accept them.
  2. Start Claude Code there and run:  /translate Project_brief.md
     It writes the digest and the spec, every line citing your answer, and
     lists as UNKNOWN whatever it could not tell. Answer those.
  3. Add the first item:  /new-item page <solution> <name>
     (or endpoint, or model — a backend-only project has no pages at all.)
  4. Fill it in, /translate it, then /build it.

  node tools/check.mjs   runs every check: briefs, specs, code map, QA's
                         suite and the round record

Commit ${RECORD}: it is how \`coperativeai update\` tells your edits from ours.
`);
}

async function update(target, dryRun) {
  const root = path.resolve(target ?? ".");
  if (!existsSync(path.join(root, "Project_brief.md"))) {
    console.log(`${root} has no Project_brief.md — run \`coperativeai init\` there first.`);
    process.exit(1);
  }
  const old = await readRecord(root);
  const record = { files: { ...(old?.files ?? {}) } };
  const added = [];
  const updated = [];
  const besides = [];
  const yours = [];
  let emitted = false;
  const shipped = new Set();

  for (const { from, to, owner } of await files(framework)) {
    shipped.add(to);
    const src = await fs.readFile(path.join(framework, from));
    const fresh = fingerprint(src);
    const dest = path.join(root, to);

    if (!existsSync(dest)) {
      added.push(to);
      if (!dryRun) await write(dest, src);
      record.files[to] = fresh;
      continue;
    }
    const current = await fs.readFile(dest);
    const now = fingerprint(current);
    if (now === fresh) {
      record.files[to] = fresh;
      continue;
    }
    if (owner === "people" && STARTER.test(current.toString("utf8"))) {
      // Still the starter, by its own header, which says it may be replaced.
      updated.push(to);
      if (!dryRun) await write(dest, src);
      record.files[to] = fresh;
      continue;
    }
    if (owner === "people") {
      // A file people fill in. Once it differs from the blank form it holds
      // somebody's answers, and no version of the form is worth more.
      yours.push(to);
      if (to === "AGENTS.md") emitted = true;
      delete record.files[to];
      continue;
    }
    // Unchanged since it was installed — by this project's record, or because
    // it is a version the framework once shipped.
    if (record.files[to] === now || (known[to] ?? []).includes(now)) {
      updated.push(to);
      if (!dryRun) await write(dest, src);
      record.files[to] = fresh;
      continue;
    }
    // Edited, or from before the record existed: there is no telling which,
    // so it is treated as edited. Kept, and the new version put beside it.
    besides.push(to);
    if (!dryRun) await write(`${dest}.update`, src);
    delete record.files[to];
  }

  // Files the framework no longer ships. Never deleted — reported, so a person
  // decides; safe to delete when nobody changed them.
  const dropped = [];
  for (const [to, print] of Object.entries(old?.files ?? {})) {
    if (shipped.has(to)) continue;
    delete record.files[to];
    const dest = path.join(root, to);
    if (!existsSync(dest)) continue;
    const untouched = fingerprint(await fs.readFile(dest)) === print;
    dropped.push(`${to}${untouched ? "  (unchanged — safe to delete)" : "  (edited since install)"}`);
  }

  const say = (done, plan) => (dryRun ? `would ${plan}` : done);
  console.log(`\n${old ? `from ${old.framework ?? "an earlier version"}` : "no install record"} → ${version}`);
  console.log(
    `${added.length} ${say("added", "add")}, ${updated.length} ${say("updated", "update")}, ${besides.length} kept yours`,
  );
  list(say("added", "add"), added);
  list(say("updated", "update"), updated);
  list(
    `kept yours, with the new version beside it as <file>.update — compare, keep one, delete the other`,
    besides,
  );
  list("yours, left alone (people's answers)", yours);
  list("no longer part of the framework — not deleted", dropped);
  if (emitted) console.log("\nAGENTS.md was written from your spec: run /emit-guardrails to pick up guardrail changes.");

  // **Specs in an old format need an AI, not a copy.** The procedures that just
  // arrived expect the Lean AI layer's files; the translation that makes them
  // is /translate's job, so this says what to run rather than guessing.
  const system = path.join(root, "ai-only/Project_system.md");
  if (existsSync(system) && !/^---\nspec:/.test((await fs.readFile(system, "utf8")).replace(/\r\n/g, "\n"))) {
    console.log(`
Your specs are in the old format. With the new procedures, re-translate them:
  /translate Project_brief.md              → Project_digest.md and Project_system.md
  /translate <solution>/application-spec.json   (each solution)
  /translate <solution>/<item>             (each item)
Then run node tools/check.mjs.`);
  }

  if (dryRun) {
    console.log("\nDry run — nothing was written. Drop --dry-run to do it.");
    return;
  }
  await writeRecord(root, record);
}

function usage() {
  console.log(`
CooperativeAICoding — a way of working that Product, Developers, QA and AI share.

  coperativeai init [folder] [--dry-run]
  coperativeai update [folder] [--dry-run]

  Installed with: npm install -g coperativeai

  init        put the brief, the forms and the commands into a project.
              Nothing that already exists is overwritten.
  update      bring the framework's files up to date. Files nobody changed
              are replaced; files you edited are kept, with the new version
              beside them as <file>.update; your answers are never touched.
  --dry-run   say what it would do, and write nothing
`);
}

const [command, ...rest] = process.argv.slice(2);
const dryRun = rest.includes("--dry-run");
const target = rest.find((a) => !a.startsWith("-"));

if (command === "init") {
  await init(target, dryRun);
} else if (command === "update") {
  await update(target, dryRun);
} else if (command === undefined || command === "--help" || command === "-h" || command === "help") {
  usage();
} else {
  console.error(`Unknown command: ${command}`);
  usage();
  process.exit(1);
}
